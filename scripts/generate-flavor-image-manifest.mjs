import { copyFileSync, existsSync, mkdirSync, readdirSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const publicDir = join(__dirname, '../public');
const flavoursDir = join(publicDir, 'flavours');

const COLLECTION_DIRS = {
  'signature-favourites': 'signature flavour collection',
  'new-flavour-collection': 'new flavour collection',
  'fall-citrus-collection': 'fall citrus collection',
  'fall-berry-collection': 'fall berry collection',
  'school-fun-collection': 'school fun collection',
};

/** Menu slug → image filename (without .png) when it differs from slugify(name). */
const FILENAME_OVERRIDES = {
  'blueberry-boardwalk-splash': 'blueberry broadwalk splash',
  'coconut-strawberry-breeze': 'coconut strawberry freeze',
  'galaxy-berry-storm': 'glaxy berry storm',
  'hawaiian-melon-punch': 'hawaiin melon punch',
  'caribbean-cherry-dream': 'carribbean cherry dream',
  'peach-berry-lime-fizz': 'peech berry lime fizz',
  'sweet-tart-galaxy': 'sweet tart collection',
  'blackberry-grape-melon': 'blacberry grape lemon',
  'strawberry-sunrise-crush': 'strawberry sunrise crunch',
  'black-cherry-bomb': 'blackberry bomb',
  'berry-candy-crush': 'berry candy rush',
};

/** Display name when it differs from titleCase(slug). */
const NAME_OVERRIDES = {
  'blue-berry-a-plus': 'Berry Apple A-Plus',
  'chrimson-cherry-trail': 'Crimson Cherry Trail',
  'mix-berry-bramble': 'Mixed Berry Bramble',
  'apple-brumble': 'Apple Bramble',
  'tropical-berry-tail': 'Tropical Berry Trail',
  'peech-mango-hearth': 'Peach Mango Hearth',
  'pasion-berry-night': 'Passion Berry Night',
  'peech-harvest-glow': 'Peach Harvest Glow',
  'peech-mango-hyride': 'Peach Mango Hayride',
  'peech-tea-sunset': 'Peach Tea Sunset',
  'passion-fruit-fall-fizz': 'Passionfruit Fall Fizz',
};

/** Collection when image folder differs from menu collection. */
const COLLECTION_OVERRIDES = {
  'grape-twilight': 'fall-berry-collection',
  'apple-brumble': 'fall-berry-collection',
  'tropical-berry-tail': 'fall-berry-collection',
  'peech-mango-hearth': 'fall-berry-collection',
  'lemonade-berry-fizz': 'fall-berry-collection',
  'watermelon-bramble': 'fall-berry-collection',
  'pasion-berry-night': 'fall-berry-collection',
};

function slugify(name) {
  return name
    .toLowerCase()
    .replace(/\.png$/i, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

function titleCase(slug) {
  return slug
    .split('-')
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
}

function displayName(slug) {
  return NAME_OVERRIDES[slug] ?? titleCase(slug);
}

function makeEntry(slug, collection, sourcePath, file) {
  return {
    slug,
    url: `/flavours/${slug}.png`,
    collection,
    name: displayName(slug),
    sourcePath,
    file,
  };
}

const bySlug = new Map();
const byCollection = {};

for (const [collection, folder] of Object.entries(COLLECTION_DIRS)) {
  const dir = join(publicDir, folder);
  let files = [];
  try {
    files = readdirSync(dir).filter((f) => f.toLowerCase().endsWith('.png'));
  } catch {
    byCollection[collection] = [];
    continue;
  }

  byCollection[collection] = [];

  for (const file of files.sort()) {
    const slug = slugify(file);
    const sourcePath = join(dir, file);
    const entry = makeEntry(slug, collection, sourcePath, file);
    bySlug.set(slug, entry);
    byCollection[collection].push(entry);
  }
}

for (const [slug, fileStem] of Object.entries(FILENAME_OVERRIDES)) {
  for (const [collection, folder] of Object.entries(COLLECTION_DIRS)) {
    const file = `${fileStem}.png`;
    const sourcePath = join(publicDir, folder, file);
    if (!existsSync(sourcePath)) continue;
    const resolvedCollection = COLLECTION_OVERRIDES[slug] ?? collection;
    bySlug.set(slug, makeEntry(slug, resolvedCollection, sourcePath, file));
    break;
  }
}

for (const [slug, entry] of bySlug.entries()) {
  const collection = COLLECTION_OVERRIDES[slug];
  if (!collection) continue;
  bySlug.set(slug, { ...entry, collection });
}

mkdirSync(flavoursDir, { recursive: true });

let copied = 0;
for (const entry of bySlug.values()) {
  if (!entry.sourcePath || !existsSync(entry.sourcePath)) continue;
  copyFileSync(entry.sourcePath, join(flavoursDir, `${entry.slug}.png`));
  copied += 1;
}

const lines = [];
lines.push('/** Auto-generated by scripts/generate-flavor-image-manifest.mjs — do not edit. */');
lines.push('');
lines.push('export interface FlavorImageEntry {');
lines.push('  slug: string;');
lines.push('  url: string;');
lines.push('  collection: string;');
lines.push('  name: string;');
lines.push('}');
lines.push('');
lines.push('export const FLAVOR_IMAGE_BY_SLUG: Record<string, FlavorImageEntry> = {');
for (const [slug, entry] of [...bySlug.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  lines.push(
    `  '${slug}': { slug: '${slug}', url: '${entry.url}', collection: '${entry.collection}', name: '${entry.name.replace(/'/g, "\\'")}' },`
  );
}
lines.push('};');
lines.push('');
lines.push('export const FLAVOR_IMAGES_BY_COLLECTION: Record<string, FlavorImageEntry[]> = {');
for (const [collection, entries] of Object.entries(byCollection)) {
  lines.push(`  '${collection}': [`);
  for (const e of entries) {
    const manifest = bySlug.get(e.slug);
    if (!manifest) continue;
    lines.push(
      `    { slug: '${manifest.slug}', url: '${manifest.url}', collection: '${collection}', name: '${manifest.name.replace(/'/g, "\\'")}' },`
    );
  }
  lines.push('  ],');
}
lines.push('};');
lines.push('');

const out = join(__dirname, '../src/lib/flavor-image-manifest.ts');
writeFileSync(out, lines.join('\n'), 'utf8');
console.log(`Wrote ${bySlug.size} flavor images to ${out}`);
console.log(`Copied ${copied} images to public/flavours/`);
